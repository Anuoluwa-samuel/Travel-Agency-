/**
 * Idempotent development seed: `pnpm db:seed`. Safe to re-run; existing rows are kept.
 * Refuses to run against production.
 *
 * Demo accounts share one password, read from SEED_DEMO_PASSWORD. If it isn't set, a random
 * one is generated and appended to .env.local (git-ignored) so it is never printed or committed.
 */
import { randomBytes } from "node:crypto";
import { appendFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { hashPassword } from "better-auth/crypto";
import { config } from "dotenv";
import { and, eq, sql } from "drizzle-orm";
import { drizzle } from "drizzle-orm/postgres-js";
import postgres from "postgres";
import { PERMISSIONS, ROLES } from "@/server/auth/permissions";
import * as s from "@/server/db/schema";
import * as data from "./data";

config({ path: ".env.local", quiet: true });

type SeedDb = ReturnType<typeof drizzle<typeof s>>;

function demoPassword(): string {
  const existing = process.env.SEED_DEMO_PASSWORD;
  if (existing && existing.length >= 10) return existing;
  const generated = randomBytes(18).toString("base64url");
  appendFileSync(
    ".env.local",
    `\n# Generated by pnpm db:seed — password for all *@orbis.example demo accounts\nSEED_DEMO_PASSWORD=${generated}\n`,
  );
  process.env.SEED_DEMO_PASSWORD = generated;
  console.log("Generated a demo password and saved it to .env.local as SEED_DEMO_PASSWORD.");
  return generated;
}

async function seedAccessControl(db: SeedDb) {
  await db
    .insert(s.permissions)
    .values(Object.entries(PERMISSIONS).map(([key, description]) => ({ key, description })))
    .onConflictDoUpdate({ target: s.permissions.key, set: { description: sql`excluded.description` } });

  await db
    .insert(s.roles)
    .values(Object.entries(ROLES).map(([key, r]) => ({ key, name: r.name, isSystem: true })))
    .onConflictDoUpdate({ target: s.roles.key, set: { name: sql`excluded.name` } });

  const roleRows = await db.select().from(s.roles);
  const permRows = await db.select().from(s.permissions);
  const permId = new Map(permRows.map((p) => [p.key, p.id]));

  // Role grants are fully replaced so removing a permission in code removes it here too.
  await db.transaction(async (tx) => {
    for (const role of roleRows) {
      const def = ROLES[role.key as keyof typeof ROLES];
      if (!def) continue;
      await tx.delete(s.rolePermissions).where(eq(s.rolePermissions.roleId, role.id));
      await tx
        .insert(s.rolePermissions)
        .values(def.permissions.map((p) => ({ roleId: role.id, permissionId: permId.get(p)! })));
    }
  });
  return new Map(roleRows.map((r) => [r.key, r.id]));
}

async function upsertUser(db: SeedDb, name: string, email: string, passwordHash: string) {
  const existing = await db
    .select({ id: s.users.id })
    .from(s.users)
    .where(eq(sql`lower(${s.users.email})`, email.toLowerCase()));
  if (existing[0]) return existing[0].id;
  const [user] = await db.insert(s.users).values({ name, email, emailVerified: true }).returning({ id: s.users.id });
  await db
    .insert(s.accounts)
    .values({ userId: user.id, accountId: user.id, providerId: "credential", password: passwordHash });
  return user.id;
}

async function seedUsers(db: SeedDb, roleIds: Map<string, string>) {
  const hash = await hashPassword(demoPassword());
  for (const staff of data.demoStaff) {
    const userId = await upsertUser(db, staff.name, data.staffEmail(staff.role), hash);
    await db.insert(s.staffProfiles).values({ userId, jobTitle: staff.title }).onConflictDoNothing();
    await db
      .insert(s.staffRoles)
      .values({ userId, roleId: roleIds.get(staff.role)! })
      .onConflictDoNothing();
  }
  const customerId = await upsertUser(db, data.demoCustomer.name, data.demoCustomer.email, hash);
  await db.insert(s.customerProfiles).values({ userId: customerId }).onConflictDoNothing();
}

async function seedGeography(db: SeedDb) {
  await db
    .insert(s.regions)
    .values([...data.regions])
    .onConflictDoNothing();
  const regionRows = await db.select().from(s.regions);
  const regionId = new Map(regionRows.map((r) => [r.slug, r.id]));
  await db
    .insert(s.countries)
    .values(
      data.countries.map((c) => ({
        iso2: c.iso2,
        name: c.name,
        regionId: regionId.get(c.region),
        currency: c.currency,
        callingCode: c.callingCode,
      })),
    )
    .onConflictDoNothing();
  await db
    .insert(s.destinationCategories)
    .values(data.categories.map((c, i) => ({ ...c, position: i })))
    .onConflictDoNothing();
}

async function seedDestinations(db: SeedDb) {
  const cats = await db.select().from(s.destinationCategories);
  const catId = new Map(cats.map((c) => [c.slug, c.id]));
  const now = new Date();

  for (const d of data.destinations) {
    const [row] = await db
      .insert(s.destinations)
      .values({
        slug: d.slug,
        name: d.name,
        countryIso2: d.countryIso2,
        city: d.city,
        kind: d.kind,
        summary: d.summary,
        overview: d.overview,
        bestMonths: [...d.bestMonths],
        suggestedDaysMin: d.days[0],
        suggestedDaysMax: d.days[1],
        budgetCurrency: "NGN",
        dailyBudgetLowMinor: d.budget[0],
        dailyBudgetMidMinor: d.budget[1],
        dailyBudgetHighMinor: d.budget[2],
        budgetSource: data.SEED_SOURCE_LABEL,
        budgetCheckedAt: now,
        isFeatured: d.featured,
        status: "published",
        publishedAt: now,
      })
      .onConflictDoNothing({ target: s.destinations.slug })
      .returning({ id: s.destinations.id });
    if (!row) continue;
    await db
      .insert(s.destinationCategoryLinks)
      .values(d.categories.map((c) => ({ destinationId: row.id, categoryId: catId.get(c)! })));
  }
}

async function seedPackage(db: SeedDb) {
  const pkg = data.demoPackage;
  const existing = await db.select({ id: s.packages.id }).from(s.packages).where(eq(s.packages.slug, pkg.slug));
  if (existing[0]) return;

  const [dest] = await db
    .select({ id: s.destinations.id })
    .from(s.destinations)
    .where(eq(s.destinations.slug, pkg.destination));
  const [policy] = await db
    .insert(s.policies)
    .values({ kind: "cancellation", ...data.cancellationPolicy })
    .onConflictDoNothing()
    .returning({ id: s.policies.id });
  const policyId =
    policy?.id ??
    (
      await db
        .select({ id: s.policies.id })
        .from(s.policies)
        .where(
          and(eq(s.policies.key, data.cancellationPolicy.key), eq(s.policies.version, data.cancellationPolicy.version)),
        )
    )[0].id;

  await db.transaction(async (tx) => {
    const now = new Date();
    const [p] = await tx
      .insert(s.packages)
      .values({
        slug: pkg.slug,
        title: pkg.title,
        summary: pkg.summary,
        description: pkg.description,
        primaryDestinationId: dest.id,
        travelStyle: pkg.travelStyle,
        durationDays: pkg.durationDays,
        nights: pkg.nights,
        dateMode: pkg.dateMode,
        bookingMode: pkg.bookingMode,
        minPax: pkg.minPax,
        maxPax: pkg.maxPax,
        meetingInfo: pkg.meetingInfo,
        cancellationPolicyId: policyId,
        isFeatured: true,
        status: "published",
        publishedAt: now,
      })
      .returning({ id: s.packages.id });

    await tx.insert(s.packageDestinations).values({ packageId: p.id, destinationId: dest.id });

    for (const day of pkg.days) {
      const [d] = await tx
        .insert(s.itineraryDays)
        .values({
          packageId: p.id,
          dayNumber: day.day,
          title: day.title,
          overnightLocation: day.overnight,
          breakfast: day.b,
          lunch: day.l,
          dinner: day.d,
        })
        .returning({ id: s.itineraryDays.id });
      await tx
        .insert(s.itineraryItems)
        .values(
          day.items.map((it, i) => ({
            itineraryDayId: d.id,
            kind: it.kind,
            title: it.title,
            isOptional: "optional" in it ? it.optional : false,
            position: i,
          })),
        );
    }

    await tx
      .insert(s.packageInclusions)
      .values([
        ...pkg.inclusions.map((text, i) => ({ packageId: p.id, kind: "included" as const, text, position: i })),
        ...pkg.exclusions.map((text, i) => ({ packageId: p.id, kind: "excluded" as const, text, position: i })),
      ]);

    const opts = await tx
      .insert(s.packageOptions)
      .values(
        pkg.options.map((o, i) => ({
          packageId: p.id,
          kind: o.kind,
          code: o.code,
          name: o.name,
          pricingBasis: o.basis,
          occupancy: o.occupancy,
          isRequired: o.required,
          position: i,
        })),
      )
      .returning({ id: s.packageOptions.id, code: s.packageOptions.code });
    const optId = new Map(opts.map((o) => [o.code, o.id]));

    await tx
      .insert(s.priceRules)
      .values(
        pkg.prices.map((pr) => ({
          packageId: p.id,
          optionId: optId.get(pr.option)!,
          travellerType: pr.traveller,
          amountMinor: pr.amount,
          currency: "NGN",
          note: "Fictional seed price",
        })),
      );

    for (const dep of pkg.departures) {
      const start = new Date(now.getTime() + dep.offsetDays * 86_400_000);
      const end = new Date(start.getTime() + (pkg.durationDays - 1) * 86_400_000);
      const deadline = new Date(start.getTime() - 21 * 86_400_000);
      await tx.insert(s.packageDepartures).values({
        packageId: p.id,
        startDate: start.toISOString().slice(0, 10),
        endDate: end.toISOString().slice(0, 10),
        bookingDeadline: deadline.toISOString().slice(0, 10),
        capacity: dep.capacity,
      });
    }

    await tx
      .insert(s.paymentPlans)
      .values({ packageId: p.id, depositBasisPoints: 3000, balanceDueDaysBefore: 45, currency: "NGN" });
  });
}

async function seedSettings(db: SeedDb) {
  await db
    .insert(s.settings)
    .values([
      { key: "brand.name", value: "ORBIS" },
      { key: "currency.base", value: "NGN" },
      { key: "timezone.business", value: "Africa/Lagos" },
      { key: "booking.deposit_bp", value: 3000 },
      { key: "staff.assigned_only_scope", value: false },
    ])
    .onConflictDoNothing();
}

export async function seed(url: string) {
  const client = postgres(url, { max: 1, onnotice: () => {} });
  const db = drizzle(client, { schema: s });
  try {
    const roleIds = await seedAccessControl(db);
    await seedUsers(db, roleIds);
    await seedGeography(db);
    await seedDestinations(db);
    await seedPackage(db);
    await seedSettings(db);
  } finally {
    await client.end();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.env.APP_ENV === "production" || process.env.APP_ENV === "staging") {
    console.error("Refusing to seed demo data outside development.");
    process.exit(1);
  }
  const url = process.env.DATABASE_URL;
  if (!url) {
    console.error("DATABASE_URL is not set");
    process.exit(1);
  }
  seed(url)
    .then(() => console.log("Seed complete."))
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
